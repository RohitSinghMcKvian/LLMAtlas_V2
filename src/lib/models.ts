// ─── Helpers ──────────────────────────────────────────────────────────────────

export function findModel(id: string): ModelSpec | undefined {
  return MODELS.find((m) => m.id === id);
}

export function getModelsByProvider(provider: ProviderId): ModelSpec[] {
  return MODELS.filter((m) => m.provider === provider);
}

export function getFreeModels(): ModelSpec[] {
  return MODELS.filter((m) => m.free);
}

export function getModelsByTag(tag: string): ModelSpec[] {
  return MODELS.filter((m) => m.tags.includes(tag));
}

export function getModelsByModality(modality: Modality): ModelSpec[] {
  return MODELS.filter((m) => m.modalities.includes(modality));
}

/** Vision-capable: takes image inputs. Derived from modalities. */
export function supportsVision(m: ModelSpec | undefined): boolean {
  return !!m && m.modalities.includes("vision");
}

/**
 * Returns true when a user must supply their own API key (BYOK) to use this model.
 * Providers that have a free server-side key bundled in the app (groq, cerebras, google,
 * pollinations) are always accessible without BYOK. Everything else requires a key.
 */
export function requiresApiKey(m: ModelSpec | undefined): boolean {
  if (!m) return false;
  // Pollinations is truly keyless — no account needed
  if (m.provider === "pollinations") return false;
  // These providers have a server-side free-tier key pre-configured in the app
  const SERVER_KEY_PROVIDERS: ProviderId[] = ["groq", "cerebras", "google"];
  if (SERVER_KEY_PROVIDERS.includes(m.provider)) return false;
  // Everything else (openrouter, github-models, nvidia, mistral, together,
  // cloudflare, huggingface, xai, deepseek) needs BYOK
  return true;
}

/** Tool/function-calling support. Derived from provider + tags. */
export function supportsTools(m: ModelSpec | undefined): boolean {
  if (!m) return false;
  const TOOL_PROVIDERS: ProviderId[] = ["groq", "openrouter", "together", "cerebras", "mistral", "google", "github-models", "xai", "deepseek"];
  if (!TOOL_PROVIDERS.includes(m.provider)) return false;
  // Exclude obviously incapable tiny models.
  if (m.tags.includes("tiny") || m.tags.includes("embedding")) return false;
  return true;
}

